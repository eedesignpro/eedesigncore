"""eedesigncore - parse, manipulate, and write KiCad 10 S-expression files.

The package root exports the six public operations (R1, ADR-045). All six share
one calling contract:

- Model objects are positional. Every other argument is keyword-only.
- ``extract_footprint`` and ``extract_symbol`` return a detached, library-clean
  copy. Neither mutates the source container.
- ``inject_footprint`` and ``inject_symbol`` append the placed model to the
  target container and return that same object.
- ``strip_uuids`` and ``generate_uuids`` change the model in place and return
  ``None``.

``__all__`` is CLOSED UNDER REACHABILITY (ADR-085, iteration 11.11). If a public
field or a public return can hand you an object, the type of that object is in
this list. ``tests/unit/test_export_surface.py`` computes the reachable set on
every run and fails when a name is missing.

The list is one flat namespace and it now carries generic short names such as
``Line``, ``Table``, ``Image``, ``Property``, ``Group``, and ``Setup``. Import
the names you need. ``from eedesigncore import *`` will shadow same-named
objects in the importing module.
"""

