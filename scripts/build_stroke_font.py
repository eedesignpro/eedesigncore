#!/usr/bin/env python
"""Generate the vendored Newstroke glyph table from the pinned KiCad clone.

KiCad's default text font is the built-in stroke font, Newstroke. Its data lives
in ``common/newstroke_font.cpp`` as one C string literal per glyph.
Vendor the complete table so schematic text keeps Unicode glyphs.
The runtime decodes only the glyphs it needs and retains each decoded result.

Run this after the pinned tag changes, and at no other time. The output is
committed, because a consumer install has no KiCad clone to read.

    python scripts/build_stroke_font.py

Point at a different clone with ``--kicad-source`` or ``$KICAD_SOURCE``.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = Path(os.environ.get("KICAD_SOURCE", "kicad-source/kicad"))
OUT = REPO / "src" / "eedesigncore" / "common" / "font" / "stroke_data.py"

# One glyph per line, as a C string literal. A trailing comment MUST be
# tolerated: the space glyph is written `"JZ", /* U+20 SPACE */`, and a pattern
# anchored at the end of the line skips it. Skipping the space shifts every
# later index by one, which silently gives every character the shape of its
# neighbour and is invisible in the output.
_LITERAL = re.compile(r'^\s*"((?:[^"\\]|\\.)*)"\s*,?\s*(?:/\*.*)?$')

# The array body, so a literal elsewhere in the file cannot enter the table.
_ARRAY_START = re.compile(r"^const char\* const newstroke_font\[\]")
_ARRAY_END = re.compile(r"^\};")

#: Glyph index of the first entry. ``dd = ord(c) - ord(' ')`` at
#: ``stroke_font.cpp:255``, so entry zero is the space.
FIRST_CHAR = " "

#: Minimum source table size, from space through tilde.
GLYPH_COUNT = ord("~") - ord(" ") + 1

_HEADER = '''"""Newstroke glyph data, generated. DO NOT EDIT.

Generated by ``scripts/build_stroke_font.py`` from KiCad {tag} at
``common/newstroke_font.cpp``. Newstroke is the font KiCad draws text with when
a text item names no other, which is every dimension in practice.

Source notices and licenses are retained in ``NEWSTROKE_LICENSE.txt``.

Each entry is one glyph, in the Hershey-derived encoding KiCad reads at
``common/font/stroke_font.cpp:132-172``:

- The first TWO characters give the horizontal extent. ``left = ord(c0) - ord('R')``
  and ``right = ord(c1) - ord('R')``, both in font units, and the advance is
  their difference.
- Every later PAIR is a point, ``x = ord(c0) - ord('R')`` and
  ``y = ord(c1) - ord('R') + FONT_OFFSET``.
- The pair ``" R"`` lifts the pen, which starts a new stroke.

Index is ``ord(character) - ord(' ')``. The table retains the complete source range.
"""

from __future__ import annotations

#: Glyph index of the first entry in :data:`GLYPHS`.
FIRST_ORDINAL = {first_ordinal}

#: One encoded glyph per source character, space first.
GLYPHS: tuple[str, ...] = (
'''


def read_glyphs(source: Path) -> list[str]:
    """Return every glyph literal from ``newstroke_font.cpp``, decoded."""
    path = source / "common" / "newstroke_font.cpp"
    if not path.is_file():
        sys.exit(f"no newstroke font at {path}")
    out: list[str] = []
    inside = False
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if not inside:
            inside = bool(_ARRAY_START.match(line))
            continue
        if _ARRAY_END.match(line):
            break
        match = _LITERAL.match(line)
        if match:
            out.append(match.group(1).encode().decode("unicode_escape"))
    return out


def read_tag(source: Path) -> str:
    """Return the checked-out tag name, or a placeholder."""
    head = source / ".git" / "HEAD"
    if head.is_file():
        text = head.read_text(encoding="utf-8", errors="replace").strip()
        if text.startswith("ref: refs/tags/"):
            return text.removeprefix("ref: refs/tags/")
        return text[:12]
    return "an unrecorded revision"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--kicad-source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()

    glyphs = read_glyphs(args.kicad_source)
    print(f"read {len(glyphs)} glyphs from the clone")
    if len(glyphs) < GLYPH_COUNT:
        sys.exit(f"expected at least {GLYPH_COUNT} glyphs, found {len(glyphs)}")

    kept = glyphs
    entries = []
    for glyph in kept:
        if len(repr(glyph)) < 90:
            entries.append(f"    {glyph!r},\n")
        else:
            chunks = [repr(glyph[i : i + 40]) for i in range(0, len(glyph), 40)]
            entries.append(
                "    (\n" + "".join(f"        {part}\n" for part in chunks) + "    ),\n"
            )
    body = "".join(entries)
    text = _HEADER.format(tag=read_tag(args.kicad_source), first_ordinal=ord(FIRST_CHAR))
    text += body + ")\n"
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")

    print(f"wrote {args.out.relative_to(REPO)}")
    print(f"  {len(kept)} glyphs, {sum(len(g) for g in kept)} characters of stroke data")
    return 0


if __name__ == "__main__":
    sys.exit(main())
